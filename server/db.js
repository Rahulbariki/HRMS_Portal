import { neon } from '@neondatabase/serverless';
import { Agent, setGlobalDispatcher } from 'undici';
import dns from 'node:dns/promises';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Configure high-availability DNS resolver using Google and Cloudflare DNS
// Prevents local router / ISP DNS REFUSED errors for cloud services
try {
  const resolver = new dns.Resolver();
  resolver.setServers(['8.8.8.8', '1.1.1.1', '8.8.4.4']);

  const agent = new Agent({
    connect: {
      lookup: (hostname, options, callback) => {
        resolver.resolve4(hostname)
          .then(addresses => {
            if (options && options.all) {
              callback(null, addresses.map(a => ({ address: a, family: 4 })));
            } else {
              callback(null, addresses[0], 4);
            }
          })
          .catch(() => {
            // Fallback to standard lookup if custom resolver misses
            import('node:dns').then(nativeDns => {
              nativeDns.lookup(hostname, options, callback);
            });
          });
      }
    }
  });

  setGlobalDispatcher(agent);
} catch (e) {
  console.warn('DNS agent configuration warning:', e.message);
}

// Load .env.local first (generated by Neon CLI), then fallback to .env
dotenv.config({ path: path.resolve(__dirname, '../.env.local') });
dotenv.config({ path: path.resolve(__dirname, '../.env') });

const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  console.error('CRITICAL: DATABASE_URL is not set in environment or .env.local');
}

export const sql = neon(connectionString);

export default sql;
